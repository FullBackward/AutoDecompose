"""Build library/INDEX.md and the reports from entries and ledgers. No network.

  py.sh build_index.py

INDEX.md lists every entry by move and language with its status (accepted
first). reports/flow.md gives the PRISMA-style flow (sources registered,
candidates, screening decisions, sites, entries by status), the coverage
matrix (move by language) and coverage of the 18 candidate rules of
survey F §10. Status is read from entry.json; nothing here changes an entry.
"""
from __future__ import annotations

from collections import Counter, defaultdict

from common import ENTRIES, LEDGER, LIB, MOVES, REPORTS, load_entries, read_json, read_jsonl

ORDER = {"accepted": 0, "verified": 1, "draft": 2, "flagged": 3, "deprecated": 4}


def scale_of(e: dict) -> str:
    """Entries before pilot-2 carry no shape; they are tactic scale."""
    return (e.get("shape") or {}).get("scale", "tactic")


def main() -> None:
    entries, unreadable = load_entries()
    if unreadable:
        print(f"# not indexed (entry.json does not parse): {', '.join(unreadable)}")
    by_move = defaultdict(list)
    for e in entries:
        by_move[e["move"]].append(e)
    out = ["# Library index", "",
           "Generated by `tools/build_index.py`; do not edit by hand. "
           "Status: accepted > verified > draft; flagged and deprecated entries are listed last.", "",
           f"{len(entries)} entries.", ""]
    for move in MOVES:
        es = sorted(by_move.get(move, []), key=lambda e: (ORDER[e["status"]], e["language"], e["id"]))
        if not es:
            continue
        out += [f"## {move}", "", "| Entry | Kind | Scale | Language | Status | Source |",
                "|---|---|---|---|---|---|"]
        for e in es:
            out.append(f"| [{e['title']}](entries/{e['id']}/README.md) | {e['kind']} | {scale_of(e)} | "
                       f"{e['language']} | {e['status']} | {e['source']['source_id']} |")
        out.append("")
    (LIB / "INDEX.md").write_text("\n".join(out), encoding="utf-8")

    sources = {r["source_id"] for r in read_jsonl(LEDGER / "sources.jsonl")}
    cands = read_jsonl(LEDGER / "candidates.jsonl")
    scr = Counter(r["decision"] for r in read_jsonl(LEDGER / "screening.jsonl"))
    sites = read_jsonl(LEDGER / "sites.jsonl")
    queries = read_jsonl(LEDGER / "queries.jsonl")
    status = Counter(e["status"] for e in entries)
    langs = sorted({e["language"] for e in entries}) or ["-"]
    rep = ["# Harvest flow and coverage", "", "Generated by `tools/build_index.py`.", "",
           "## Flow", "",
           f"- Queries run: {len(queries)}",
           f"- Candidate sources found: {len(cands)}",
           f"- Sources registered (pinned): {len(sources)}",
           f"- Screening decisions: " + (", ".join(f"{k} {v}" for k, v in scr.items()) or "none"),
           f"- Candidate sites: {len(sites)}",
           f"- Entries: " + (", ".join(f"{k} {v}" for k, v in sorted(status.items())) or "none"),
           f"- By scale: " + ", ".join(f"{k} {v}" for k, v in sorted(Counter(scale_of(e) for e in entries).items())), "",
           "## Coverage: move by language (accepted / verified / all)", "",
           "Verified entries passed every check but still have an open review objection.", "",
           "| Move | " + " | ".join(langs) + " |", "|---" * (len(langs) + 1) + "|"]
    for move in MOVES:
        cells = []
        for lang in langs:
            es = [e for e in entries if e["move"] == move and e["language"] == lang]
            acc = sum(e["status"] == "accepted" for e in es)
            ver = sum(e["status"] == "verified" for e in es)
            cells.append(f"{acc} / {ver} / {len(es)}" if es else ".")
        rep.append(f"| {move} | " + " | ".join(cells) + " |")
    rules = defaultdict(lambda: Counter())
    for e in entries:
        r = (e.get("rule") or {})
        if r.get("f10_rule"):
            rules[r["f10_rule"]][(r.get("relation"), e["status"])] += 1
    rep += ["", "## Coverage of survey F §10 rules", "",
            "| Rule | supports (accepted / all) | contradicts (accepted / all) |", "|---|---|---|"]
    for n in range(1, 19):
        c = rules.get(n, Counter())
        sa = c[("supports", "accepted")]; st = sum(v for (rel, _), v in c.items() if rel == "supports")
        ca = c[("contradicts", "accepted")]; ct = sum(v for (rel, _), v in c.items() if rel == "contradicts")
        rep.append(f"| {n} | {sa} / {st} | {ca} / {ct} |")
    REPORTS.mkdir(parents=True, exist_ok=True)
    (REPORTS / "flow.md").write_text("\n".join(rep) + "\n", encoding="utf-8")
    print(f"INDEX.md: {len(entries)} entries; reports/flow.md written")


if __name__ == "__main__":
    main()
