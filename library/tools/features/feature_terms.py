def md_table(header, rows):
    out = ["| " + " | ".join(header) + " |", "|" + "|".join("---" for _ in header) + "|"]
    for r in rows:
        out.append("| " + " | ".join("" if x is None else str(x) for x in r) + " |")
    return "\n".join(out)


def pct(a, b):
    return "n/a" if not b else f"{a}/{b} ({100 * a / b:.0f}%)"


def bucket(n, edges=(0, 2, 5)):
    if n is None:
        return "null"
    if n <= edges[0]:
        return str(edges[0])
    if n <= edges[1]:
        return f"{edges[0] + 1}-{edges[1]}"
    if n <= edges[2]:
        return f"{edges[1] + 1}-{edges[2]}"
    return f"{edges[2] + 1}+"


def cross(records, key, moves, order=None):
    """Counts of key(record) by move, as table rows; rows sorted by total, then by name."""
    c = Counter()
    for r in records:
        c[(key(r), r["t0"]["move"])] += 1
    vals = sorted({v for v, _m in c}, key=lambda v: (-sum(c[(v, m)] for m in moves), str(v)))
    if order:
        vals = [v for v in order if v in vals] + [v for v in vals if v not in order]
    return [[str(v)] + [c[(v, m)] or "" for m in moves] + [sum(c[(v, m)] for m in moves)] for v in vals]


