def sx(node):
    """Compact text of a skeleton node, used by the self-test and by hand audits."""
    if node["k"] == "stmt":
        bs = " ".join(f"{b['b']}:{b['n']}" + (f"<{b['t']}>" if b.get("t") else "") for b in node["binders"])
        hs = " ".join("H<" + sx(h) + ">" for h in node["hyps"])
        return f"[{bs}] {hs} |- " + " || ".join(sx(c) for c in node["c"])
    extra = ""
    for key in ("op", "h", "n"):
        if key in node:
            extra += f":{node[key]}"
    for key in ("bounded", "meta", "sb", "u", "v"):
        if node.get(key):
            extra += f"[{key}]"
    if node.get("c"):
        return "(" + node["k"] + extra + " " + " ".join(sx(c) for c in node["c"]) + ")"
    return node["k"] + extra


