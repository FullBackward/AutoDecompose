def self_test():
    bad = 0

    def check(ok, label, got=None, want=None):
        nonlocal bad
        if not ok:
            bad += 1
            print(f"FAIL {label}\n  got:  {got}\n  want: {want}")

    for lang, st, want, reason in STATEMENT_CASES:
        a = analyse_statement(st, lang)
        got = sx(a["skeleton"]) if a.get("ok") else None
        check(got == want and a.get("null_reason") == reason, f"statement [{lang}] {st[:50]!r}",
              (got, a.get("null_reason")), (want, reason))
    for lang, st, text, want in DETECTOR_CASES:
        d = detect_snippet(lang, st, text)
        for name, exp in sorted(want.items()):
            check(d[name]["fires"] is exp, f"detector {name} [{lang}] {text[:40]!r}", d[name], exp)
    for lang, st, want in FLAT_CASES:
        a = analyse_statement(st, lang)
        got = {k: (a.get("f") or {}).get(k) for k in want}
        check(got == want, f"flat [{lang}] {st[:50]!r}", got, want)
    for name, ids, want in CITE_CASES:
        check(cites_name(name, ids) is want, f"cites_name {name!r} in {ids}", cites_name(name, ids), want)
    for case in HEAD_CASES:
        lang, text, want = case[:3]
        p = proof_record(text, lang)
        check(p["heads"] == want, f"heads [{lang}] {text[:40]!r}", p["heads"], want)
        if len(case) > 3:
            check((p["closing"] or {}).get("head") == case[3], f"closing [{lang}] {text[:40]!r}", p["closing"], case[3])
    # every head of the class table has exactly one class (checked at import) and every class is known
    for lang, tab in L.CLASS_TABLE.items():
        for cls in tab:
            check(cls in L.CLASSES, f"class table [{lang}] unknown class {cls}")
    # determinism: two builds of the same entry give the same bytes
    ids = entry_ids()[:3]
    for eid in ids:
        check(dump(build_record(eid)) == dump(build_record(eid)), f"determinism {eid}")
    n = (len(STATEMENT_CASES) + len(FLAT_CASES) + sum(len(w) for _a, _b, _c, w in DETECTOR_CASES)
         + len(HEAD_CASES) + sum(len(c) > 3 for c in HEAD_CASES) + len(CITE_CASES) + len(ids))
    print(f"self-test: {n - bad} passed, {bad} failed")
    return 1 if bad else 0


# ============================================================================= main

def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("entry", nargs="?", help="an entry id: print its record")
    ap.add_argument("--all", action="store_true", help="write features/term-features.jsonl")
    ap.add_argument("--check", action="store_true", help="recompute and compare with the committed output")
    ap.add_argument("--report", action="store_true", help="print the validation tables")
    ap.add_argument("--write-report", action="store_true", help="refresh the generated block of features/terms.md")
    ap.add_argument("--self-test", action="store_true")
    a = ap.parse_args()
    if a.self_test:
        sys.exit(self_test())
    if a.entry:
        if not (ENTRIES / a.entry / "entry.json").is_file():
            print(f"error: no entry {a.entry}", file=sys.stderr)
            sys.exit(2)
        print(json.dumps(build_record(a.entry), ensure_ascii=False, sort_keys=True, indent=1))
        return
    if not (a.all or a.check or a.report or a.write_report):
        ap.print_help()
        sys.exit(2)
    records = build_all()
    text = render_jsonl(records)
    block = report(records)
    if a.report:
        sys.stdout.write(block)
    if a.all:
        write_text(OUT, text)
        print(f"wrote {OUT.relative_to(LIB.parent).as_posix()}: {len(records)} records, "
              f"sha256 {sha256(text.encode('utf-8'))}", file=sys.stderr)
    if a.write_report:
        if not DOC.is_file():
            print(f"error: {DOC.name} does not exist", file=sys.stderr)
            sys.exit(2)
        new = doc_with_block(DOC.read_bytes().decode("utf-8").replace("\r\n", "\n"), block)
        if new is None:
            print(f"error: {DOC.name} has no generated block marks", file=sys.stderr)
            sys.exit(2)
        write_text(DOC, new)
        print(f"wrote {DOC.relative_to(LIB.parent).as_posix()}: sha256 {sha256(new.encode('utf-8'))}",
              file=sys.stderr)
    if a.check:
        rc = 0
        if not OUT.is_file():
            print(f"check: {OUT.name} is missing")
            rc = 1
        else:
            old_raw = OUT.read_bytes()
            old = old_raw.replace(b"\r\n", b"\n").decode("utf-8")
            if old != text:
                rc = 1
                o = {json.loads(ln)["id"]: ln for ln in old.splitlines() if ln.strip()}
                nw = {json.loads(ln)["id"]: ln for ln in text.splitlines()}
                diff = sorted(k for k in set(o) | set(nw) if o.get(k) != nw.get(k))
                print(f"check: {OUT.name} differs in {len(diff)} record(s): " + ", ".join(diff[:10])
                      + (" ..." if len(diff) > 10 else ""))
            else:
                note = " (line ends converted by the checkout)" if old_raw != text.encode("utf-8") else ""
                print(f"check: {OUT.name} is up to date{note}, sha256 {sha256(text.encode('utf-8'))}")
        if DOC.is_file():
            doc = DOC.read_bytes().decode("utf-8").replace("\r\n", "\n")
            new = doc_with_block(doc, block)
            if new is None:
                print(f"check: {DOC.name} has no generated block")
            elif new != doc:
                rc = 1
                print(f"check: the generated block of {DOC.name} is stale")
            else:
                print(f"check: the generated block of {DOC.name} is up to date")
        sys.exit(rc)


if __name__ == "__main__":
    main()
