def relation(parent, child):
    """Parent-to-child features from two analysed statements."""
    if not parent.get("ok"):
        return {"ok": False, "null_reason": "parent-statement-null"}
    if not child.get("ok"):
        return {"ok": False, "null_reason": "child-statement-null"}
    pf, cf = parent["f"], child["f"]
    pc, chc = set(parent["consts"]), set(child["consts"])
    inter, union = pc & chc, pc | chc
    pb, cb = parent["_bound"], child["_bound"]
    conj = iff_dir = iff_side = None
    ccore = canon(child["_core_toks"], cb) if child["_core_toks"] else None
    cconcl = canon(child["_concl_toks"], cb) if child["_concl_toks"] else None
    parts = [(k, canon(t, pb)) for k, t in parent["_parts"]]
    if ccore is not None:
        ands = [c for k, c in parts if k == "and"]
        if ands:
            conj = ccore in ands or cconcl in ands
        iffs = [c for k, c in parts if k == "iff"]
        if len(iffs) == 2:
            a, b = iffs
            iff_side = "lhs" if ccore == a else "rhs" if ccore == b else None
            hyp = child["_hyp_canon"]
            iff_dir = "mp" if ccore == b and a in hyp else "mpr" if ccore == a and b in hyp else None
    core_in_parent = None
    if child["_core_toks"]:
        need = [t.t for t in L._strip_parens(child["_core_toks"])]
        hay = parent["_type_text"]
        core_in_parent = bool(need) and any(hay[i:i + len(need)] == need for i in range(len(hay) - len(need) + 1))
    key_p, key_c = pf.get("family_key"), cf.get("family_key")
    p_nums, c_nums = set(parent["numerals"]), set(child["numerals"])
    return {
        "ok": True, "null_reason": None,
        "n_shared_consts": len(inter), "n_parent_only_consts": len(pc - chc), "n_child_only_consts": len(chc - pc),
        "jaccard_consts": round(len(inter) / len(union), 6) if union else None,
        "same_core_class": pf.get("core_class") is not None and pf.get("core_class") == cf.get("core_class"),
        "same_core_head": pf.get("core_head") is not None and pf.get("core_head") == cf.get("core_head"),
        "same_family_key": key_p is not None and key_p == key_c,
        "child_is_conjunct": conj, "child_core_is_iff_side": iff_side, "child_is_iff_direction": iff_dir,
        "child_core_in_parent": core_in_parent,
        "d_bound_all": cf["n_bound_all"] - pf["n_bound_all"], "d_hyps": cf["n_hyps"] - pf["n_hyps"],
        "d_tokens": cf["n_tokens"] - pf["n_tokens"],
        "more_bound": cf["n_bound_all"] > pf["n_bound_all"], "fewer_bound": cf["n_bound_all"] < pf["n_bound_all"],
        "more_hyps": cf["n_hyps"] > pf["n_hyps"], "fewer_hyps": cf["n_hyps"] < pf["n_hyps"],
        "introduces_consts": bool(chc - pc),
        "parent_numerals_absent": len(p_nums - c_nums),
    }


def name_affix(names):
    """Longest common prefix and suffix of the names (in characters), each as a share of the shortest name."""
    names = [n for n in names if n]
    if len(names) < 2:
        return None, None
    lo = min(len(n) for n in names)
    p = 0
    while p < lo and len({n[p] for n in names}) == 1:
        p += 1
    s = 0
    while s < lo - p and len({n[-1 - s] for n in names}) == 1:
        s += 1
    return round(p / lo, 6), round(s / lo, 6)


