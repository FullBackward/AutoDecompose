NO_SIGNATURE = ["key-invariant", "extract-have", "other"]


def _last(name):
    return name.split(".")[-1]


def cites_name(name, ids):
    """Does a body identifier cite the declaration `name`? The last component of `name` must occur as a
    whole dotted component of some identifier, so that Lean dot notation on a lemma (`foo.2`, `foo.mp`,
    `foo.trans_le`, `x.foo y`) counts and a longer name (`foo_aux`) does not."""
    last = _last(name)
    return any(x == name or last in x.split(".") for x in ids)


def run_detectors(lang, kind, glue, parent, children, sites, texts, has_skill_text, parent_name, parent_file):
    """All detectors for one entry. glue: {"scope", "heads", "classes", "toks", "info", "body_ids"} or None.
    Returns {name: {"fires": bool or None, "null_reason": .., "signals": {signal: value}}}."""
    out = {}

    def put(name, fires, signals, null_reason=None):
        out[name] = {"fires": fires, "null_reason": null_reason, "signals": dict(sorted(signals.items()))}

    code_null = None
    if lang not in PROVER:
        code_null = "not-prover-language"
    elif glue is None or glue["scope"] == "none":
        code_null = "no-glue-proof"
    pf = parent["f"] if parent.get("ok") else {}
    core = pf.get("core_class")
    if code_null:
        for name in ("induction", "case-split", "iff-split", "witness", "extensionality", "calc-chain",
                     "suffices-or-strengthen"):
            put(name, None, {}, code_null)
    else:
        heads, classes, toks, info = glue["heads"], glue["classes"], glue["toks"], glue["info"]
        ids = [t.t for t in toks if t.k == "id"]
        lasts = [_last(x) for x in ids]
        cls = Counter(classes)
        nested = {k: lang == "rocq" and any(x in v for x in ids) for k, v in ROCQ_NESTED.items()}

        s = {"tactic": cls["induction"] > 0, "nested-tactic": nested["induction"] and not cls["induction"],
             "recursor-name": any(RX_INDUCTION.search(x) for x in lasts)
             or (lang == "rocq" and any(RX_INDUCTION_ROCQ.search(x) for x in lasts)),
             "self-reference": bool(parent_name) and lang == "lean"
             and any(x == parent_name or x == _last(parent_name) for x in ids)}
        put("induction", s["tactic"] or s["nested-tactic"] or s["recursor-name"] or s["self-reference"], s)

        split_mod = False
        if lang == "isabelle":
            for i, t in enumerate(toks):
                if t.k == "id" and t.t == "split" and i + 1 < len(toks) and (
                        toks[i + 1].t == ":" or (toks[i + 1].t == "!" and i + 2 < len(toks) and toks[i + 2].t == ":")):
                    split_mod = True
        s = {"tactic": cls["case-split"] > 0, "nested-tactic": nested["case-split"] and not cls["case-split"],
             "alt-pattern": info.get("alt", 0) > 0, "split-modifier": split_mod,
             "or-elim-name": any(x in OR_ELIM or _last(x) in ("disjE", "orP") for x in ids)}
        put("case-split", s["tactic"] or s["nested-tactic"] or s["alt-pattern"] or s["split-modifier"]
            or s["or-elim-name"], s)

        anon_pairs = anon_any = 0
        if lang == "lean":
            for i, t in enumerate(toks):
                if t.k == "open" and t.t == "⟨" and (i == 0 or toks[i - 1].t in ANON_BEFORE):
                    e = L._group_end(toks, i)
                    commas = sum(1 for u in toks[i + 1:e] if u.t == "," and u.depth == t.depth + 1)
                    anon_any += commas >= 1
                    anon_pairs += commas == 1
        isar_dirs = lang == "isabelle" and heads.count("next") >= 1 and heads.count("assume") >= 2
        s = {"goal-iff": core == "iff",
             "constructor": any(h in ("constructor", "split", "iff_intro") for h in heads)
             or (lang == "isabelle" and any(x in ("iffI", "standard") for x in ids)),
             "anon-pair": anon_pairs > 0, "isar-directions": bool(isar_dirs),
             "iff-intro-name": any(x in IFF_INTRO or _last(x) in ("iffI", "iffP") for x in ids),
             "antisymm-name": any(RX_ANTISYMM.search(x) for x in lasts)}
        put("iff-split", (s["goal-iff"] and (s["constructor"] or s["anon-pair"] or s["isar-directions"]))
            or s["iff-intro-name"] or s["antisymm-name"], s)

        s = {"goal-exists": core in ("exists", "exists-unique"), "tactic": cls["witness"] > 0,
             "anon-constructor": anon_any > 0,
             "exists-intro-name": any(x in WITNESS_NAMES or _last(x) in ("exI", "bexI", "ex1I") for x in ids),
             "obtain-or-set": cls["obtain"] > 0 or any(h in ("set", "pose", "define", "let") for h in heads)}
        put("witness", s["tactic"] or (s["goal-exists"] and s["anon-constructor"]) or s["exists-intro-name"], s)

        s = {"tactic": cls["ext"] > 0, "ext-name": any(RX_EXT[lang].search(x) for x in lasts)}
        put("extensionality", s["tactic"] or s["ext-name"], s)

        n_trans = sum(1 for x in lasts if RX_TRANS.search(x))
        run = best = 0
        for c in classes:
            run = run + 1 if c == "rewrite" else 0
            best = max(best, run)
        s = {"calc-block": cls["calc"] > 0 or any(x == "calc" for x in ids), "n-trans-names": n_trans,
             "longest-rewrite-run": best, "calc-steps": info.get("calc_steps", 0)}
        put("calc-chain", s["calc-block"] or n_trans >= 2, s)

        s = {"tactic": cls["suffices"] > 0 or any(x in ("suffices", "wlog") for x in ids)}
        put("suffices-or-strengthen", s["tactic"], s)

    # sorry tokens in any parent, child or skeleton site
    read = [x for x in sites if x["proof"].get("n_sorry") is not None]
    if lang not in PROVER or not read:
        put("sorrify-at-failure", None, {}, "not-prover-language" if lang not in PROVER else "no-site-read")
    else:
        n = sum(x["proof"]["n_sorry"] for x in read)
        put("sorrify-at-failure", n > 0, {"sorry-token": n})

    # blueprint markup in any copied file
    marks = 0
    for path in sorted(texts):
        t = texts[path]
        if path.endswith(".tex"):
            marks += len(re.findall(r"\\(?:uses|lean|leanok)\b", t))
        elif path.endswith(".lean"):
            marks += len(re.findall(r"@\[\s*blueprint\b", t))
    put("blueprint-node", marks > 0, {"blueprint-markup": marks})

    # one theorem in the parent's file
    if lang != "lean" or parent_file is None or parent_file not in texts:
        put("statement-object", None, {}, "not-lean" if lang != "lean" else "no-parent-site")
    else:
        ft = L.lex_lean(L.blank_comments(texts[parent_file], "lean"))
        n_thm = sum(1 for t in ft if t.depth == 0 and t.k == "id" and t.t in ("theorem", "lemma", "problem")
                    and L._decl_position(ft, t))
        put("statement-object", n_thm == 1, {"theorems-in-file": n_thm})

    put("workflow", kind == "skill" or has_skill_text, {"skill-kind": kind == "skill",
                                                        "skill-text-site": has_skill_text})

    # API attributes on parent and child sites
    if lang not in PROVER or not read:
        put("interface-lemma", None, {}, "not-prover-language" if lang not in PROVER else "no-site-read")
    else:
        n_api = sum(1 for x in read if x["proof"].get("n_api_attrs", 0) > 0)
        put("interface-lemma", n_api >= 2, {"api-attr-sites": n_api})

    # relation detectors need parsed child statements
    stated = [c for c in children if c["statement"].get("ok")]
    if lang not in PROVER or not stated:
        nr = "not-prover-language" if lang not in PROVER else "no-child-statement"
        put("per-callee-lemma", None, {}, nr)
        put("generalise-then-instantiate", None, {}, nr if lang not in PROVER or not parent.get("ok") or not stated
            else None)
    else:
        keys = Counter(c["statement"]["f"]["family_key"] for c in stated if c["statement"]["f"].get("family_key"))
        size = max(keys.values(), default=0)
        share = round(size / len(stated), 6)
        put("per-callee-lemma", size >= 3 and share >= 0.6, {"family-size": size, "family-share": share})
        if not parent.get("ok"):
            put("generalise-then-instantiate", None, {}, "no-parent-statement")
        else:
            gen = [c for c in stated if c["rel"].get("ok") and c["rel"]["same_family_key"] and c["rel"]["more_bound"]
                   and (c["rel"]["n_parent_only_consts"] > 0 or c["rel"]["parent_numerals_absent"] > 0)]
            put("generalise-then-instantiate", bool(gen), {"generalising-child": len(gen)})
    return dict(sorted(out.items()))


