def doc_with_block(doc, block):
    a, b = doc.find(BEGIN_MARK), doc.find(END_MARK)
    if a < 0 or b < 0 or b < a:
        return None
    return doc[:a + len(BEGIN_MARK)] + "\n\n" + block + "\n" + doc[b:]


