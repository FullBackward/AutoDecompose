def proof_record(text, lang):
    """Proof-text features of one site, with the private read result under `_read`."""
    r = L.read_site(text, lang)
    heads = [h for _ln, h in r["heads"]]
    classes = [L.classify_head(h, lang) for h in heads]
    hist = dict(sorted(Counter(classes).items()))
    core = [c for c in classes if c not in IGNORED_FOR_AUTO]
    blank = L.blank_comments(text, lang)
    has_proof = bool(heads) and r["mode"] != "none"
    words = SORRY_WORDS[lang]
    n_sorry = sum(1 for t in r["toks"] if t.k in ("id", "sym") and t.t in words)
    rec = {
        "ok": has_proof, "null_reason": None if has_proof else "no-proof-text",
        "mode": r["mode"], "dialect": r["dialect"], "n_decls": len(r["decls"]),
        "n_code_lines": sum(1 for ln in blank.split("\n") if ln.strip()),
        "n_tokens": r["n_tokens"], "n_body_tokens": len(r["body"]),
        "n_heads": len(heads), "heads": heads, "classes": classes, "hist": hist,
        "closing": {"head": r["closing"], "class": L.classify_head(r["closing"], lang)} if r["closing"] else None,
        "closes_by_automation_alone": (bool(core) and all(c == "automation" for c in core)) if has_proof else None,
        "closes_by_automation_or_trivial": (bool(core) and all(c in ("automation", "trivial-close") for c in core))
        if has_proof else None,
        "closing_is_automation": (L.classify_head(r["closing"], lang) == "automation") if r["closing"] else None,
        "share_unclassified": round(classes.count("unclassified") / len(classes), 6) if classes else None,
        "n_sorry": n_sorry, "n_api_attrs": count_api_attrs(r["toks"], lang),
        "info": dict(sorted(r["info"].items())),
        "_read": r,
    }
    return rec


def count_api_attrs(toks, lang):
    """Attributes and commands that register a lemma with automation or a class: `@[simp]`, `[simp]`, `Hint`,
    `Canonical`, `instance`, `declare`, `lemmas`. A token pattern."""
    n = 0
    for i, t in enumerate(toks):
        if lang == "lean":
            if t.t == "@" and i + 1 < len(toks) and toks[i + 1].t == "[":
                e = L._group_end(toks, i + 1)
                n += any(u.k == "id" and u.t in API_ATTRS for u in toks[i + 2:e])
            elif t.k == "id" and t.t == "instance" and t.depth == 0 and t.first:
                n += 1
        elif lang == "rocq":
            if t.k == "id" and t.t in ("Hint", "Canonical", "Coercion", "Instance") and (i == 0 or toks[i - 1].k == "dot"
                                                                                       or toks[i - 1].t in L.ROCQ_MODS
                                                                                       or toks[i - 1].t == "]"):
                n += 1
        else:
            if t.k == "open" and t.t == "[" and i and toks[i - 1].k == "id" and t.depth == 0:
                e = L._group_end(toks, i)
                n += any(u.k == "id" and u.t in API_ATTRS for u in toks[i + 1:e])
            elif t.k == "id" and t.t in ("declare", "lemmas", "instance", "interpretation", "sublocale",
                                         "global_interpretation") and t.depth == 0 and t.first:
                n += 1
    return n


def site_record(s, texts, lang):
    a, b = s["lines"]
    rec = {"role": s.get("role"), "name": s.get("name"), "path": s["path"], "lines": [a, b], "n_lines": b - a + 1}
    if s.get("role") not in READ_ROLES:
        rec["proof"] = {"ok": False, "null_reason": "role-not-read"}
    elif lang not in PROVER or path_lang(s["path"]) != lang:
        rec["proof"] = {"ok": False, "null_reason": "not-prover-text"}
    else:
        text = site_text(texts, s)
        if text is None:
            rec["proof"] = {"ok": False, "null_reason": "file-missing"}
        else:
            rec["proof"] = proof_record(text, lang)
    return rec


