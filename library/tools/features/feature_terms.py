    flat["d_n_child_proofs"] = len(child_proofs) if prover else None
    flat["d_n_children_automation_alone"] = sum(bool(p["closes_by_automation_alone"]) for p in child_proofs) \
        if prover else None
    flat["d_n_children_automation_or_trivial"] = sum(bool(p["closes_by_automation_or_trivial"])
                                                     for p in child_proofs) if prover else None
