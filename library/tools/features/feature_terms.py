def norm_ws(s):
    return " ".join(s.split())


def sha256(b):
    return hashlib.sha256(b).hexdigest()


def entry_ids():
    return sorted(p.name for p in ENTRIES.iterdir() if (p / "entry.json").is_file())


def load_entry(eid):
    """(entry, input digest, texts by recorded path, files_ok).

    The digest is SHA-256 over entry.json (CRLF read as LF, so that a checkout with line-ending conversion
    gives the digest of the committed blob) followed by the recorded file hashes, sorted, one per line.
    files_ok is True when every recorded file is present with the recorded SHA-256."""
    raw = (ENTRIES / eid / "entry.json").read_bytes().replace(b"\r\n", b"\n")
    e = json.loads(raw.decode("utf-8"))
    h = hashlib.sha256(raw)
    for x in sorted(f.get("sha256", "") for f in e.get("files") or []):
        h.update(b"\n" + x.encode("ascii", "replace"))
    texts, ok = {}, True
    for f in e.get("files") or []:
        p = ENTRIES / eid / "code" / f["path"]
        if not p.is_file():
            ok = False
            continue
        b = p.read_bytes()
        if sha256(b) != f.get("sha256"):
            ok = False
        texts[f["path"]] = b.decode("utf-8", "replace").replace("\r\n", "\n")
    return e, h.hexdigest(), texts, ok


def path_lang(path):
    for lang, ext in EXT.items():
        if path.endswith(ext):
            return lang
    return None


def site_text(texts, s):
    t = texts.get(s["path"])
    if t is None:
        return None
    a, b = s["lines"]
    return "\n".join(t.split("\n")[a - 1:b])


