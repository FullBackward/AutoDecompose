def clean(node, bound):
    """Copy a parsed tree for output: private keys dropped, heads that are bound names marked and unnamed."""
    out = {"k": node["k"]}
    for key in ("op", "sym", "h", "n", "a", "f", "bounded", "meta", "chain", "sb", "u", "asc", "g", "neg",
                "explicit", "note", "obtains"):
        if key in node:
            out[key] = node[key]
    for key in ("h", "f"):
        h = out.get(key)
        if isinstance(h, str) and out["k"] in ("app", "const", "expr"):
            first = h.split(".")[0]
            if h in bound or (first and first in bound):
                rest = h[len(first):] if first in bound else ""
                if key == "f":
                    del out["f"]
                    continue
                out["v"] = 1
                if rest and not re.fullmatch(r"(?:\.\d+)+", rest):
                    out["h"] = rest
                    if out["k"] == "const":
                        out["k"], out["a"] = "app", 0
                elif out["k"] == "const":
                    out["k"] = "var"
                    del out["h"], out["v"]
                else:
                    del out["h"]
    if node.get("c"):
        out["c"] = [clean(c, bound) for c in node["c"]]
    return out


def node_class(n):
    k = n["k"]
    if k == "rel":
        return "rel:" + n["op"]
    if k in ("const", "app"):
        if n.get("h") == "False" and not n.get("a"):
            return "false"
        if n.get("h") == "True" and not n.get("a"):
            return "true"
        return "app"
    if k == "bracket":
        return "set-builder" if n.get("sb") else "bracket"
    return k


def head_of(n):
    """Head of a cleaned node: the head constant of an application, `rel:<op>` for a relation, else its class."""
    k = n["k"]
    if k in ("app", "const"):
        return n.get("h") if not n.get("v") or n.get("h", "").startswith(".") else "«var»"
    if k == "triple":
        return "triple"
    if k == "expr" and n.get("f"):
        return n["f"]
    return node_class(n)


def family_key(n):
    """What two statements must share to count as the same conclusion form (terms.md, `family key`)."""
    k = n["k"]
    if k in ("app", "const") and n.get("h") and not (n.get("v") and not n["h"].startswith(".")):
        return "app:" + n["h"]
    if k == "expr" and n.get("f"):
        return "app:" + n["f"]
    if k == "triple":
        return "triple"
    if k == "rel":
        a, b = (head_of(c) for c in n["c"][:2])
        if a not in ("«var»", "var", "num", "expr") or b not in ("«var»", "var", "num", "expr"):
            return f"rel:{n['op']}:{a}:{b}"
    return None


def strip_spine(n):
    """(core, spine forall slots, premises, lets): peel leading universal binders, implication premises and lets."""
    foralls, premises, lets = 0, [], 0
    while True:
        k = n["k"]
        if k == "forall" and n.get("c"):
            foralls += n.get("n", 0)
            n = n["c"][0]
        elif k == "arrow" and n.get("c"):
            premises += n["c"][:-1]
            n = n["c"][-1]
        elif k == "let" and n.get("c"):
            lets += n.get("n", 1)
            n = n["c"][0]
        else:
            return n, foralls, premises, lets


def quant_prefix(n):
    seq = []
    while True:
        k = n["k"]
        if k == "forall" and n.get("c"):
            seq.append("A")
            n = n["c"][0]
        elif k in ("exists", "exists-unique") and n.get("c"):
            seq.append("E")
            n = n["c"][0]
        elif k in ("arrow", "let") and n.get("c"):
            n = n["c"][-1]
        else:
            break
    out = []
    for q in seq:
        if not out or out[-1] != q:
            out.append(q)
    return "".join(out)


def quant_alternations(n, pol=1, last=None):
    """Largest number of changes between universal and existential binders along a path from the root.
    A binder under a negation or on the left of an implication counts with the opposite kind."""
    k, cur = n["k"], None
    if k == "forall":
        cur = "A" if pol > 0 else "E"
    elif k in ("exists", "exists-unique"):
        cur = "E" if pol > 0 else "A"
    add = 1 if cur and last and cur != last else 0
    nl, best = cur or last, 0
    kids = n.get("c") or []
    for i, c in enumerate(kids):
        cp = -pol if k == "not" or (k == "arrow" and i < len(kids) - 1) else pol
        best = max(best, quant_alternations(c, cp, nl))
    return add + best


def tree_stats(n, depth=1, acc=None):
    acc = acc if acc is not None else {"size": 0, "depth": 0, "kinds": Counter(), "unknown_leaves": 0, "leaves": 0}
    acc["size"] += 1
    acc["depth"] = max(acc["depth"], depth)
    acc["kinds"][n["k"]] += 1
    if not n.get("c"):
        acc["leaves"] += 1
        if n.get("u") or n["k"] in ("cut", "empty", "prefix") or n.get("note"):
            acc["unknown_leaves"] += 1
    for c in n.get("c") or []:
        tree_stats(c, depth + 1, acc)
    return acc


def canon(toks, bound):
    """Token text of a span with bound names replaced by #0, #1, .. in order of first occurrence."""
    toks = L._strip_parens(toks)
    seen, out = {}, []
    for t in toks:
        x = t.t
        if t.k == "id":
            first = x.split(".")[0]
            if first in bound:
                if first not in seen:
                    seen[first] = f"#{len(seen)}"
                x = seen[first] + x[len(first):]
        out.append(x)
    return " ".join(out)


def _isabelle_type_skip(toks):
    """Indices of tokens that belong to a `:: type` annotation in Isabelle inner syntax."""
    skip, i, n = set(), 0, len(toks)
    while i < n:
        if toks[i].t == "::":
            d, j = toks[i].depth, i + 1
            while j < n:
                u = toks[j]
                if u.depth < d or (u.depth == d and u.k == "close"):
                    break
                if u.depth == d and u.k == "sym" and L._isa_base(u.t) not in ("\\<Rightarrow>", "=>", "\\<times>", "*"):
                    break
                skip.add(j)
                j += 1
            i = j
        else:
            i += 1
    return skip


def analyse_statement(text, lang, corpus=None, ctx_vars=None):
    """Features of one statement. Returns a dict with ok/null_reason, the output skeleton and flat features,
    and private fields (keys starting with `_`) used for the relation features."""
    if lang not in PROVER:
        return {"ok": False, "null_reason": "not-prover-language"}
    if text is None:
        return {"ok": False, "null_reason": "statement-null"}
    if corpus is not None and norm_ws(text) not in corpus:
        return {"ok": False, "null_reason": "not-verbatim"}
    parsed, reason = L.parse_statement(text, lang)
    if parsed is None:
        return {"ok": False, "null_reason": reason}
    cfg = L.TERM[lang]
    budget = L._Budget()
    toks = parsed["toks"]
    bound = set()
    for b in parsed["binders"]:
        bound.update(b["names"])
    bound.update(parsed.get("obtains") or [])
    scanned, n_sb, n_big = L.scan_forms(toks, lang)
    bound.update(scanned)
    for b in parsed["binders"]:
        if b["type"]:
            bound.update(L.scan_forms(b["type"], lang)[0])

    raw_binders = [(b, L.parse_term(b["type"], lang, budget) if b["type"] else None) for b in parsed["binders"]]
    raw_hyps = [L.parse_term(h, lang, budget) for h in parsed["hyps"]]
    raw_concls = [L.parse_term(c, lang, budget) for c in parsed["concl"]]

    binders, n_prop, n_named, n_hyp_binders = [], 0, 0, 0
    kinds = Counter()
    for b, ty in raw_binders:
        cty = clean(ty, bound) if ty is not None else None
        cls = node_class(cty) if cty is not None else None
        prop = cls is not None and (cls in PROP_FORM or cls.startswith("rel:"))
        named = lang != "isabelle" and b["typed"] and not prop and b["kind"] == "explicit" and (
            not b["names"] or all(re.match(r"[hH]", nm) for nm in b["names"]))
        if cls in ("app", "var", "expr", "bracket", "arrow", "atom", "num") and cty is not None and \
                cty["k"] == "const" and cty.get("h") in cfg["sorts"] | _SORTS_EXTRA:
            cls = "sort"
        n_prop += prop
        n_named += named
        n_hyp_binders += prop or named
        kinds[b["kind"]] += b["n"]
        rec = {"b": b["kind"], "n": b["n"], "t": cls}
        if cls == "app" and cty is not None and cty.get("h") and not cty.get("v"):
            rec["h"] = cty["h"]
        binders.append(rec)

    hyps = [clean(h, bound) for h in raw_hyps]
    cc = [clean(c, bound) for c in raw_concls]
    if parsed.get("obtains") is not None and cc:
        body = cc[0] if len(cc) == 1 else {"k": "and", "c": cc}
        concl = {"k": "exists", "n": len(parsed["obtains"]), "obtains": 1, "c": [body]}
    elif len(cc) == 1:
        concl = cc[0]
    elif len(cc) > 1:
        concl = {"k": "multi", "c": cc}
    else:
        concl = None

    f = {"decl_kind": parsed["decl_kind"], "form": parsed["form"], "n_decls": parsed["n_decls"],
         "n_binder_groups": len(binders), "n_bound_names": sum(b["n"] for b in binders),
         "n_explicit": kinds["explicit"] + kinds["fixes"], "n_implicit": kinds["implicit"],
         "n_strict_implicit": kinds["strict-implicit"], "n_instance": kinds["instance"],
         "n_let_binders": kinds["let"],
         "n_binders_prop_form": n_prop, "n_binders_hyp_named": n_named, "n_assumes": len(hyps),
         "n_tokens": len(toks), "max_bracket_depth": max((t.depth + (t.k == "open") for t in toks), default=0),
         "n_set_builder": n_sb, "n_bigop": n_big, "n_shows": len(cc)}

    private = {"_bound": bound, "_hyp_canon": set(), "_core_toks": None, "_parts": [], "_concl_toks": None,
               "_type_text": [t.t for part in parsed["concl"] for t in part]}
    for b, ty in raw_binders:
        if ty is not None:
            private["_hyp_canon"].add(canon(b["type"], bound))
    for h in parsed["hyps"]:
        private["_hyp_canon"].add(canon(h, bound))

    if concl is None:
        f.update({"concl_class": None, "core_class": None, "core_class10": None, "core_head": None,
                  "family_key": None, "n_premises": 0, "n_spine_forall": 0, "n_hyps": n_hyp_binders + len(hyps),
                  "quant_prefix": None, "quant_alternations": None, "tree_size": None, "tree_depth": None,
                  "n_tokens_concl": 0, "share_unknown_leaves": None})
        skeleton = {"k": "stmt", "decl": parsed["decl_kind"], "form": parsed["form"], "binders": binders,
                    "hyps": hyps, "c": []}
        null_part = "no-type"
    else:
        core, n_forall, premises, n_lets = strip_spine(concl)
        st = tree_stats(concl)
        f.update({"concl_class": node_class(concl), "core_class": node_class(core),
                  "core_class10": CLASS10.get(node_class(core), "other"), "core_head": head_of(core),
                  "family_key": family_key(core), "n_premises": len(premises), "n_spine_forall": n_forall,
                  "n_hyps": n_hyp_binders + len(hyps) + len(premises),
                  "quant_prefix": quant_prefix(concl), "quant_alternations": quant_alternations(concl),
                  "tree_size": st["size"], "tree_depth": st["depth"],
                  "n_tokens_concl": sum(len(c) for c in parsed["concl"]),
                  "share_unknown_leaves": round(st["unknown_leaves"] / st["leaves"], 6) if st["leaves"] else None})
        for key in ("forall", "exists", "exists-unique", "lambda", "let", "ite", "and", "or", "iff", "not", "arrow",
                    "rel"):
            f["n_" + key.replace("-", "_")] = st["kinds"][key]
        if core["k"] == "rel":
            f["core_rel_sides"] = [head_of(c) for c in core["c"][:2]]
        # private spans for the relation features: the raw core and its conjuncts or iff sides
        if len(raw_concls) == 1 and parsed.get("obtains") is None:
            rcore, _f, rprem, _l = strip_spine(raw_concls[0])
            private["_core_toks"] = rcore["_t"]
            private["_concl_toks"] = raw_concls[0]["_t"]
            for p in rprem:
                private["_hyp_canon"].add(canon(p["_t"], bound))
            if rcore["k"] in ("and", "iff") and rcore.get("c"):
                private["_parts"] = [(rcore["k"], c["_t"]) for c in rcore["c"]]
        elif len(raw_concls) > 1:
            private["_parts"] = [("and", c["_t"]) for c in raw_concls]
        skeleton = {"k": "stmt", "decl": parsed["decl_kind"], "form": parsed["form"], "binders": binders,
                    "hyps": hyps, "c": [concl]}
        null_part = None
    f["truncated"] = budget.truncated

    # identifiers that no binder of the statement binds
    skip = _isabelle_type_skip(toks) if lang == "isabelle" else set()
    free, fields, nums, n_sorts = Counter(), Counter(), Counter(), 0
    for i, t in enumerate(toks):
        if i in skip:
            continue
        if t.k == "num":
            nums[t.t] += 1
            continue
        if t.k != "id" or t.t in cfg["kw"] or t.t == "_" or t.t.startswith("?"):
            continue
        x = t.t
        first = x.split(".")[0]
        if x in bound or (first and first in bound):
            rest = x[len(first):] if first in bound and x not in bound else ""
            if rest and not re.fullmatch(r"(?:\.\d+)+", rest):
                fields[rest] += 1
            continue
        if x in cfg["sorts"] or re.sub(r"\.\{.*\}$", "", x) in cfg["sorts"]:
            n_sorts += 1
            continue
        free[x] += 1
    ctx = set(ctx_vars or [])
    ctx_used = sorted(x for x in free if x in ctx or x.split(".")[0] in ctx)
    consts = {x: n for x, n in free.items() if x not in set(ctx_used)}
    f.update({"n_free_idents": len(free), "n_free_ident_occurrences": sum(free.values()),
              "n_ctx_vars": len(ctx_used) if ctx_vars is not None else None,
              "n_consts": len(consts), "n_numerals": sum(nums.values()), "n_distinct_numerals": len(nums),
              "n_sorts": n_sorts, "n_field_uses": sum(fields.values()),
              "n_bound_all": f["n_bound_names"] + f["n_spine_forall"]})
    out = {"ok": True, "null_reason": None, "skeleton": skeleton, "f": f,
           "consts": dict(sorted(consts.items())), "ctx_vars_used": ctx_used if ctx_vars is not None else None,
           "fields": dict(sorted(fields.items())), "numerals": sorted(nums),
           "partial": null_part}
    out.update(private)
    return out


def public(rec):
    return {k: v for k, v in rec.items() if not k.startswith("_")}


