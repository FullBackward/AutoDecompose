    rows.append(["total"] + [sum(cl[lg].values()) for lg in PROVER])
    add(md_table(["class"] + list(PROVER), rows))
    add("")
    for lg in PROVER:
        top = sorted(un[lg].items(), key=lambda kv: (-kv[1], kv[0]))[:20]
        add(f"Most frequent unclassified heads, {lg}: " + (", ".join(f"`{h}` {n}" for h, n in top) or "none") + ".")
        add("")

    # ---- notation defeat
    add("### G10. Where notation defeats the statement parser")
    add("")
