def detect_snippet(lang, statement, text):
    """Run the detectors on one statement and one site text, as build_record does for an entry."""
    parent = analyse_statement(statement, lang)
    proof = proof_record(text, lang)
    site = {"role": "parent", "name": "t", "path": "t" + EXT[lang], "lines": [1, text.count("\n") + 1],
            "n_lines": text.count("\n") + 1, "proof": proof}
    r = proof["_read"]
    toks = r["body"]
    glue = {"scope": "sites" if r["heads"] else "none", "heads": [h for _l, h in r["heads"]],
            "classes": [L.classify_head(h, lang) for _l, h in r["heads"]], "toks": toks, "info": dict(r["info"]),
            "body_ids": [t.t for t in toks if t.k == "id"]}
    return run_detectors(lang, "instance", glue, parent, [], [site], {}, False, None, None)


